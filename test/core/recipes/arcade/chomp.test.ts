describe('chomper on its 11x5 grid', () => {
  it.each(Object.keys(PINNED))('keeps the approved %s frames', (variant) => {
    expect(toOutputText(VARIANTS_A[variant](GRID, { variant }), GRID.cols)).toEqual(PINNED[variant]);
  });
});

describe('chomp variants', () => {
  it('cross the grid once per loop, one column a frame', () => {
    GRIDS.forEach((grid) => {
      expect(VARIANTS_A.chomp(grid, { variant: 'chomp' }).frames).toHaveLength(grid.cols);
    });
  });

  it('lay pellets on the even columns ahead of the mouth, on its middle row', () => {
    GRIDS.forEach((grid) => {
      const [frame] = VARIANTS_A['chomp-rest'](grid, { variant: 'chomp-rest' }).frames;
      const size = grid.rows >= 5 ? 5 : 3;
      const middle = Math.floor((grid.rows - size) / 2) + Math.floor(size / 2);
      const lit = frame.flatMap((bit, index) => (bit === 1 && index % grid.cols >= size ? [index] : []));
      const expected = Array.from({ length: grid.cols }, (_, x) => x)
        .filter((x) => x >= size && x % 2 === 0)
        .map((x) => middle * grid.cols + x);
      expect(lit).toEqual(expected);
    });
  });

  it('leave only the chaser once the caught mouth collapses', () => {
    GRIDS.forEach((grid) => {
      const { frames } = VARIANTS_A['chomp-caught'](grid, { variant: 'chomp-caught' });
      expect(countLit(frames[frames.length - 1])).toBe(CHASER_CELLS);
    });
  });
});
