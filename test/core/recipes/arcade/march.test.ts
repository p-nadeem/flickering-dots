describe('alien-march on its 9x8 grid', () => {
  it.each(Object.keys(PINNED))('keeps the approved %s frames', (variant) => {
    expect(toOutputText(VARIANTS_A[variant](GRID, { variant }), GRID.cols)).toEqual(PINNED[variant]);
  });
});

describe('march variants', () => {
  it('keep the cannon still while the formation marches', () => {
    GRIDS.forEach((grid) => {
      const { frames } = VARIANTS_A.march(grid, { variant: 'march' });
      frames.forEach((frame) => expect(bottomRows(frame, grid)).toEqual(bottomRows(frames[0], grid)));
    });
  });

  it('add aliens across wider grids and ranks down taller ones', () => {
    const counts = [
      { cols: 9, rows: 8 },
      { cols: 13, rows: 8 },
      { cols: 13, rows: 11 },
      { cols: 16, rows: 16 },
    ].map(
      (grid) =>
        (countLit(VARIANTS_A.march(grid, { variant: 'march' }).frames[0]) - CANNON_CELLS) / ALIEN_CELLS,
    );
    expect(counts).toEqual([2, 3, 6, 9]);
  });

  it('end the clear state on an empty sky over the lifted cannon', () => {
    GRIDS.forEach((grid) => {
      const { frames } = VARIANTS_A['march-clear'](grid, { variant: 'march-clear' });
      const last = frames[frames.length - 1];
      expect(countLit(last)).toBe(CANNON_CELLS);
      expect(last.slice((grid.rows - 1) * grid.cols).every((bit) => bit === 0)).toBe(true);
    });
  });
});
