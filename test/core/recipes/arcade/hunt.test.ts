describe('snake-hunt on its 8x8 grid', () => {
  it.each(Object.keys(PINNED))('keeps the approved %s frames', (variant) => {
    expect(toOutputText(VARIANTS_A[variant](GRID, { variant }), GRID.cols)).toEqual(PINNED[variant]);
  });
});

describe('hunt variants', () => {
  it('take one lap of the cycle per loop, growing to min(12, cells / 3) and back to 3', () => {
    const broken = GRIDS.filter((grid) => {
      const { frames, durations } = VARIANTS_A.hunt(grid, { variant: 'hunt' });
      const longest = Math.min(LONGEST_CAP, Math.floor((grid.cols * grid.rows) / 3));
      const counts = frames.map(countLit);
      const loopMs = durations.reduce((sum, ms) => sum + ms, 0);
      return (
        loopMs < getHuntCycle(grid).length * STEP_MS ||
        Math.max(...counts) < longest ||
        Math.max(...counts) > longest + FOOD ||
        counts[0] > START_LENGTH + FOOD ||
        counts[0] < START_LENGTH
      );
    });
    expect(broken.map(label)).toEqual([]);
  });

  it('fill every cell before draining around the check, even when both sides are odd', () => {
    GRIDS.forEach((grid) => {
      const { frames } = VARIANTS_A['hunt-fill'](grid, { variant: 'hunt-fill' });
      expect(Math.max(...frames.map(countLit))).toBe(grid.cols * grid.rows);
      expect(frames[frames.length - 1]).toEqual(glyphMask('check', grid));
    });
  });

  it('blink twice after the crash and hold the crashed snake', () => {
    GRIDS.forEach((grid) => {
      const { frames, durations } = VARIANTS_A['hunt-crash'](grid, { variant: 'hunt-crash' });
      const blinks = durations.flatMap((ms, index) => (ms === 250 ? [countLit(frames[index]) === 0] : []));
      expect(blinks).toEqual([false, true, false, true]);
      expect(countLit(frames[frames.length - 1])).toBeGreaterThan(0);
    });
  });
});
