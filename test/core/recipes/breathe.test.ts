import { describe, expect, it } from 'vitest';

import { generateBreathe } from '../../../src/core/recipes/breathe';

import { toOutputText } from './frame-text';

describe('generateBreathe', () => {
  it('breathes in about two seconds on 5x5', () => {
    expect(toOutputText(generateBreathe({ cols: 5, rows: 5 }), 5)).toEqual({
      frames: [
        '00000 00000 00100 00000 00000',
        '00000 01110 01110 01110 00000',
        '11111 11111 11111 11111 11111',
        '00000 01110 01110 01110 00000',
      ],
      durations: [700, 280, 700, 280],
    });
  });

  it('holds each end on 7x3', () => {
    expect(toOutputText(generateBreathe({ cols: 7, rows: 3 }), 7)).toEqual({
      frames: ['0000000 0001000 0000000', '0011100 0011100 0011100'],
      durations: [700, 700],
    });
  });

  it('steps through every square on 9x9', () => {
    expect(toOutputText(generateBreathe({ cols: 9, rows: 9 }), 9)).toEqual({
      frames: [
        '000000000 000000000 000000000 000000000 000010000 000000000 000000000 000000000 000000000',
        '000000000 000000000 000000000 000111000 000111000 000111000 000000000 000000000 000000000',
        '000000000 000000000 001111100 001111100 001111100 001111100 001111100 000000000 000000000',
        '000000000 011111110 011111110 011111110 011111110 011111110 011111110 011111110 000000000',
        '111111111 111111111 111111111 111111111 111111111 111111111 111111111 111111111 111111111',
        '000000000 011111110 011111110 011111110 011111110 011111110 011111110 011111110 000000000',
        '000000000 000000000 001111100 001111100 001111100 001111100 001111100 000000000 000000000',
        '000000000 000000000 000000000 000111000 000111000 000111000 000000000 000000000 000000000',
      ],
      durations: [700, 280, 280, 280, 700, 280, 280, 280],
    });
  });
});
